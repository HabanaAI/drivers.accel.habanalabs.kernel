#ifndef GAUDI_SIMULATOR_H
#define GAUDI_SIMULATOR_H


#define GAUDI_SIM_SHMEM_SIZE		SZ_512M			/* 512 MB */
#define GAUDI_SIM_DMA_POOL_BLK_SIZE	SZ_256			/* 256 bytes */
#define GAUDI_SIM_PCI_OUTSTANDING	128

#define GAUDI_SIM_RW_REG_TIMEOUT_US	5000000			/* 5s */
#define GAUDI_SIM_MMU_TIMEOUT_USEC	(MMU_CONFIG_TIMEOUT_USEC * 100)

#define GAUDI_SIM_CB_POOL_CB_CNT	64
#define GAUDI_SIM_CB_POOL_CB_SIZE	SZ_4K			/* 4KB */

#define GAUDI_SIM_HALT_WAIT_MSEC	500			/* 500ms */
#define GAUDI_SIM_RESET_WAIT_MSEC	5000			/* 5000ms */

#define GAUDI_SIM_NIC_QPC_INV_USEC	5000000			/* 5s */


/* DRAM Memory Map */
#define GAUDI_SIM_CPU_FW_IMAGE_SIZE	0x00000000ull	/* 0MB */
#define GAUDI_SIM_MMU_PAGE_TABLES_SIZE	0x0BF00000ull	/* 191MB */
#define GAUDI_SIM_MMU_CACHE_MNG_SIZE	0x00100000ull	/* 1MB */
#define GAUDI_SIM_NIC_DRV_SIZE		0x04000000ull	/* 64MB */

#define GAUDI_SIM_CPU_FW_IMAGE_ADDR	DRAM_PHYS_BASE
#define GAUDI_SIM_MMU_PAGE_TABLES_ADDR	(GAUDI_SIM_CPU_FW_IMAGE_ADDR + \
						GAUDI_SIM_CPU_FW_IMAGE_SIZE)
#define GAUDI_SIM_MMU_CACHE_MNG_ADDR	(GAUDI_SIM_MMU_PAGE_TABLES_ADDR + \
						GAUDI_SIM_MMU_PAGE_TABLES_SIZE)
#define GAUDI_SIM_NIC_DRV_ADDR		(GAUDI_SIM_MMU_CACHE_MNG_ADDR + \
						GAUDI_SIM_MMU_CACHE_MNG_SIZE)
#define GAUDI_SIM_DRAM_DRV_END_ADDR	(GAUDI_SIM_NIC_DRV_ADDR + \
						GAUDI_SIM_NIC_DRV_SIZE)

#define GAUDI_SIM_DRAM_BASE_ADDR_USER	0x10000000ull

#if (GAUDI_SIM_DRAM_DRV_END_ADDR > GAUDI_SIM_DRAM_BASE_ADDR_USER)
#error "SIM driver must reserve no more than 256MB"
#endif


/* NIC memory map */
#define GAUDI_SIM_NIC_DRV_BASE_ADDR	ALIGN(GAUDI_SIM_NIC_DRV_ADDR, \
						SECTION_ALIGN_SIZE)

#define GAUDI_SIM_REQ_QPC_BASE_ADDR	GAUDI_SIM_NIC_DRV_BASE_ADDR

#define GAUDI_SIM_RES_QPC_BASE_ADDR	ALIGN(GAUDI_SIM_REQ_QPC_BASE_ADDR + \
						NIC_NUMBER_OF_ENGINES * \
						REQ_QPC_BASE_SIZE, \
						SECTION_ALIGN_SIZE)

#define GAUDI_SIM_TMR_BASE_ADDR		ALIGN(GAUDI_SIM_RES_QPC_BASE_ADDR + \
						NIC_NUMBER_OF_ENGINES * \
						RES_QPC_BASE_SIZE, \
						SECTION_ALIGN_SIZE)

#define GAUDI_SIM_TXS_BASE_ADDR		ALIGN(GAUDI_SIM_TMR_BASE_ADDR + \
						NIC_NUMBER_OF_MACROS * \
						TMR_BASE_SIZE, \
						SECTION_ALIGN_SIZE)

#define GAUDI_SIM_SWQ_BASE_ADDR		ALIGN(GAUDI_SIM_TXS_BASE_ADDR + \
						NIC_NUMBER_OF_ENGINES * \
						TXS_BASE_SIZE, \
						SECTION_ALIGN_SIZE)

#define GAUDI_SIM_SB_BASE_ADDR		ALIGN(GAUDI_SIM_SWQ_BASE_ADDR + \
						NIC_NUMBER_OF_PORTS * \
						SWQ_BASE_SIZE, \
						SECTION_ALIGN_SIZE)

#define GAUDI_SIM_NIC_DRV_END_ADDR	ALIGN(GAUDI_SIM_SB_BASE_ADDR + \
						NIC_NUMBER_OF_PORTS * \
						SB_BASE_SIZE, \
						SECTION_ALIGN_SIZE)


#endif /* GAUDI_SIMULATOR_H */
