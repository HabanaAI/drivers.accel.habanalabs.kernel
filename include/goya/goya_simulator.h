#ifndef GOYA_SIMULATOR_H
#define GOYA_SIMULATOR_H


#define GOYA_SHMEM_SIZE			SZ_256M		/* 256 MB */
#define GOYA_SIM_DMA_POOL_BLK_SIZE	SZ_256		/* 256 bytes */
#define GOYA_SIM_PCI_OUTSTANDING	128

#define GOYA_SIM_RW_REG_TIMEOUT_US	5000000		/* 5s */
#define GOYA_SIM_MMU_TIMEOUT_USEC	(MMU_CONFIG_TIMEOUT_USEC * 100)

#define GOYA_SIM_CB_POOL_CB_CNT		64
#define GOYA_SIM_CB_POOL_CB_SIZE	SZ_4K		/* 4KB */

#define GOYA_SIM_HALT_WAIT_MSEC		500		/* 500ms */
#define GOYA_SIM_RESET_WAIT_MSEC	5000		/* 5000ms */


/* DRAM Memory Map */
#define GOYA_SIM_CPU_FW_IMAGE_SIZE		0ull
#define GOYA_SIM_MMU_PAGE_TABLES_SIZE		0x03D00000ull	/* 61MB */
#define GOYA_SIM_MMU_DRAM_DEFAULT_PAGE_SIZE	0x00200000ull	/* 2MB */
#define GOYA_SIM_MMU_CACHE_MNG_SIZE		0x00001000ull	/* 4KB */

#define GOYA_SIM_CPU_FW_IMAGE_ADDR	0ull
#define GOYA_SIM_MMU_PAGE_TABLES_ADDR	(GOYA_SIM_CPU_FW_IMAGE_ADDR + \
					GOYA_SIM_CPU_FW_IMAGE_SIZE)

#define GOYA_SIM_MMU_DRAM_DEFAULT_PAGE_ADDR \
					(GOYA_SIM_MMU_PAGE_TABLES_ADDR + \
					GOYA_SIM_MMU_PAGE_TABLES_SIZE)

#define GOYA_SIM_MMU_CACHE_MNG_ADDR	(GOYA_SIM_MMU_DRAM_DEFAULT_PAGE_ADDR + \
					GOYA_SIM_MMU_DRAM_DEFAULT_PAGE_SIZE)

#define GOYA_SIM_DRAM_KMD_END_ADDR	(GOYA_SIM_MMU_CACHE_MNG_ADDR + \
					GOYA_SIM_MMU_CACHE_MNG_SIZE)

#define GOYA_SIM_DRAM_BASE_ADDR_USER	0x04000000ull

#if (GOYA_SIM_DRAM_KMD_END_ADDR > GOYA_SIM_DRAM_BASE_ADDR_USER)
#error "KMD must reserve no more than 64MB"
#endif

#endif /* GOYA_SIMULATOR_H */
