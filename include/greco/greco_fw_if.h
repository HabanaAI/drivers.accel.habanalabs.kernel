#ifndef GRECO_FW_IF_H
#define GRECO_FW_IF_H

#define GRECO_EVENT_QUEUE_MSIX_IDX	0

#define UBOOT_FW_OFFSET			0x100000	/* 1MB in SRAM */
#define LINUX_FW_OFFSET			0x800000	/* 8MB in DDR */

enum greco_fw_status {
	GRECO_PID_STATUS_UP = 0x1,	/* PID on ARC0 is up */
	GRECO_ARM_STATUS_UP = 0x2,	/* ARM Linux Boot complete */
	GRECO_MGMT_STATUS_UP = 0x3,	/* ARC1 Mgmt is up */
	GRECO_STATUS_LAST = 0xFF
};

#define GRECO_PLL_FREQ_LOW		200000000 /* 200 MHz */

#define GRECO_SP_SRAM_BASE_ADDR		0x1BFE0000
#define GRECO_MAILBOX_BASE_ADDR		0x1BFE8000

#define GRECO_ARCPID_TX_MB_SIZE		0x1000
#define GRECO_ARCPID_RX_MB_SIZE		0x400
#define GRECO_ARM_TX_MB_SIZE		0x400
#define GRECO_ARM_RX_MB_SIZE		0x1800

#define GRECO_ARCPID_TX_MB_ADDR		GRECO_MAILBOX_BASE_ADDR

#define GRECO_ARCPID_RX_MB_ADDR		(GRECO_ARCPID_TX_MB_ADDR +	\
					GRECO_ARCPID_TX_MB_SIZE)

#define GRECO_ARM_TX_MB_ADDR		(GRECO_ARCPID_RX_MB_ADDR +	\
					GRECO_ARCPID_RX_MB_SIZE)

#define GRECO_ARM_RX_MB_ADDR		(GRECO_ARM_TX_MB_ADDR +	\
					GRECO_ARM_TX_MB_SIZE)

#define GRECO_ARM_TX_MB_OFFSET		(GRECO_ARM_TX_MB_ADDR - \
					GRECO_SP_SRAM_BASE_ADDR)

#define GRECO_ARM_RX_MB_OFFSET		(GRECO_ARM_RX_MB_ADDR - \
					GRECO_SP_SRAM_BASE_ADDR)

#endif /* GRECO_FW_IF_H */
